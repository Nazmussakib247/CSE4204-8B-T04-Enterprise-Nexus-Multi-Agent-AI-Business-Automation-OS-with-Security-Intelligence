const supabase = require('../config/supabase');
const { generateAnalyticsReport } = require('../utils/gemini');
const { writeAuditLog } = require('../utils/audit');
const { getStoreSalesSummary } = require('../utils/storeSales');

// GET /api/analytics/reports
const getReports = async (req, res, next) => {
  try {
    const { page = 1, limit = 20 } = req.query;
    const offset = (page - 1) * limit;

    const { data, error, count } = await supabase
      .from('analytics_reports')
      .select('*', { count: 'exact' })
      .order('created_at', { ascending: false })
      .range(offset, offset + Number(limit) - 1);

    if (error) throw error;
    res.json({ data, total: count, page: Number(page), limit: Number(limit) });
  } catch (err) {
    next(err);
  }
};

// GET /api/analytics/reports/:id
const getReport = async (req, res, next) => {
  try {
    const { data, error } = await supabase
      .from('analytics_reports')
      .select('*')
      .eq('id', req.params.id)
      .single();

    if (error || !data) return res.status(404).json({ error: 'Report not found' });
    res.json({ data });
  } catch (err) {
    next(err);
  }
};

// POST /api/analytics/reports — manual create
const createReport = async (req, res, next) => {
  try {
    const { performance_rating, overall_score, ai_insights, action_items, kpi_snapshot } = req.body;

    const { data, error } = await supabase
      .from('analytics_reports')
      .insert({
        user_id: req.user.id,
        performance_rating,
        overall_score,
        ai_insights,
        action_items,
        kpi_snapshot,
      })
      .select()
      .single();

    if (error) throw error;
    res.status(201).json({ message: 'Analytics report created', data });
  } catch (err) {
    next(err);
  }
};

// POST /api/analytics/generate — Gemini cross-module KPI report
const generateReport = async (req, res, next) => {
  try {
    const userId = req.user.id;

    // Office analytics is based on shared organisational data.
    const [hrRes, financeRes, supportRes] = await Promise.all([
      supabase.from('hr_reports').select('recommendation, ai_score, job_title').order('created_at', { ascending: false }).limit(50),
      supabase.from('finance_records').select('category, amount, severity').order('created_at', { ascending: false }).limit(50),
      supabase.from('support_tickets').select('urgency, sentiment, status, escalated').order('created_at', { ascending: false }).limit(50),
    ]);

    const aiResult = await generateAnalyticsReport({
      hr: hrRes.data || [],
      finance: financeRes.data || [],
      support: supportRes.data || [],
    });

    const { data, error } = await supabase
      .from('analytics_reports')
      .insert({
        user_id: userId,
        performance_rating: aiResult.performance_rating,
        overall_score: aiResult.overall_score,
        ai_insights: aiResult.ai_insights,
        action_items: aiResult.action_items,
        kpi_snapshot: aiResult.kpi_snapshot,
      })
      .select()
      .single();

    if (error) throw error;

    writeAuditLog({
      userId,
      action: 'analytics.report.generate',
      resourceType: 'analytics_report',
      resourceId: data.id,
      req,
    });

    res.status(201).json({ message: 'Analytics report generated by AI', data, ai_analysis: aiResult });
  } catch (err) {
    next(err);
  }
};

// GET /api/analytics/kpi — latest KPI snapshot
const getLatestKPI = async (req, res, next) => {
  try {
    const { data, error } = await supabase
      .from('analytics_reports')
      .select('kpi_snapshot, overall_score, performance_rating, created_at')
      .order('created_at', { ascending: false })
      .limit(1)
      .maybeSingle();

    if (error) throw error;
    if (data) return res.json({ data, source: 'saved_report' });

    // Keep the Analytics page useful before the first AI report is generated.
    // This snapshot is deterministic and reads the same live business tables.
    const [hrRes, financeRes, supportRes, sales] = await Promise.all([
      supabase.from('hr_reports').select('recommendation, ai_score'),
      supabase.from('finance_records').select('is_anomaly, severity'),
      supabase.from('support_tickets').select('status, escalated, sentiment'),
      getStoreSalesSummary(),
    ]);
    if (hrRes.error) throw hrRes.error;
    if (financeRes.error) throw financeRes.error;
    if (supportRes.error) throw supportRes.error;
    const hr = hrRes.data || []; const finance = financeRes.data || []; const support = supportRes.data || [];
    const highRisk = finance.filter((item) => item.is_anomaly || item.severity === 'high').length;
    const openTickets = support.filter((item) => item.status !== 'resolved').length;
    const negativeTickets = support.filter((item) => item.sentiment === 'negative').length;
    const score = Math.max(0, Math.min(100, 100 - highRisk * 12 - openTickets * 4 - negativeTickets * 5));
    const rating = score >= 85 ? 'excellent' : score >= 70 ? 'good' : score >= 50 ? 'average' : 'poor';
    res.json({
      source: 'live_snapshot',
      data: {
        id: 'live', created_at: new Date().toISOString(), overall_score: score, performance_rating: rating,
        ai_insights: 'Live KPI snapshot. Generate an AI Report for a saved Groq analysis and recommendations.',
        kpi_snapshot: {
          store_revenue: sales.total_revenue, booked_orders: sales.order_count,
          candidates_screened: hr.length, finance_anomalies: highRisk,
          open_tickets: openTickets, negative_sentiment_tickets: negativeTickets,
        },
      },
    });
  } catch (err) {
    next(err);
  }
};

// DELETE /api/analytics/reports/:id
const deleteReport = async (req, res, next) => {
  try {
    const { error } = await supabase
      .from('analytics_reports')
      .delete()
      .eq('id', req.params.id);

    if (error) throw error;
    res.json({ message: 'Report deleted' });
  } catch (err) {
    next(err);
  }
};

module.exports = { getReports, getReport, createReport, generateReport, getLatestKPI, deleteReport };
